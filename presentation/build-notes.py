#!/usr/bin/env python3
"""Regenerates speaker-notes.md from deck.json and the <aside> of each slide,
with the time budget per slide. Run after editing a slide: ./build-notes.py"""
import html
import json
import re

# Minutes per slide. Demos are included; the total must stay within 50 minutes
# with room for questions.
BUDGET = {
    "cover": 0.5, "question": 1, "why-bpf": 1, "name": 1, "what": 0.75, "lifecycle": 1.25,
    "languages": 0.75, "verifier": 1.25, "hooks": 1, "probes-sysfs": 0.75,
    "maps": 1.25, "overhead": 1.25,
    "try": 0.5, "ex01": 0.75, "oneliner-open": 0.5, "ex03": 0.5, "ex04": 0.5,
    "oneliner-latency": 0.75, "ex06": 0.75, "ex07": 0.75, "demo-bpftrace": 3,
    "kernel-versions": 1, "core": 1.5, "ex12": 0.75, "ex11": 1.5,
    "go-build": 1, "go-gallery": 0.75,
    "toolbox": 0.5, "stap-grid": 1,
    "containers": 0.75, "k8s-workflow": 1.5, "storeiops-kernel": 1.5,
    "storeiops-user": 1.25, "demo-k8s": 4,
    "production": 1, "llm": 1.5, "ior-llm": 5, "reading": 0.5, "next-steps": 0.5,
}
LIMIT = 50


def mmss(m):
    return f"{int(m)}:{int(round((m - int(m)) * 60)):02d}"


deck = json.load(open("deck.json"))
starts = {v["start"]: (k, v["description"]) for k, v in deck["sections"].items()}
out = ["# eBPF for SREs: slide outline, timing and speaker notes", "",
       "Generated by `build-notes.py` from the slide files in `slides/`, in deck order.", ""]
rows, total, body = [], 0.0, []
for i, sid in enumerate(deck["order"], 1):
    src = open(f"slides/{sid}.html").read()
    title = re.search(r"<h[12][^>]*>(.*?)</h[12]>", src, re.S).group(1)
    title = html.unescape(re.sub(r"<[^>]+>", " ", title)).replace("  ", " ").strip()
    note = html.unescape(re.search(r"<aside>(.*?)</aside>", src, re.S).group(1)).strip()
    mins = BUDGET[sid]
    if sid in starts:
        body += [f"## Section: {starts[sid][0]}", "", f"_{starts[sid][1]}_", ""]
    body += [f"### {i}. {title}", "", f"`{sid}` · {mmss(mins)} min · starts at {mmss(total)}", "", note, ""]
    rows.append(f"| {i} | {title} | {mmss(mins)} | {mmss(total)} |")
    total += mins
assert total <= LIMIT, f"deck runs {total} min"
out += [f"**Total: {mmss(total)} min including both demos, leaving {mmss(LIMIT - total)} min of the "
        f"{LIMIT} for questions.** The Go example shown in depth is 13 (storeiops); the others are a flyover "
        "(slides ex11 and go-gallery). Three demos: bpftrace, the Kubernetes workflow with storeiops, "
        "and ior + an LLM. See `demo-plan.md`.", "",
        "| # | Slide | Time | Starts at |", "|---|---|---|---|"] + rows + [""] + body
open("speaker-notes.md", "w").write("\n".join(out))
print(f"{len(deck['order'])} slides, {mmss(total)} min")
